// Scores Spotter against labelled clips: for each eval/labels/*.labels.json with a matching video in
// eval/clips/, re-runs the analysis frame by frame in headless Chromium and compares with the labels.
// Writes eval/report.md and eval/report.json.
//
//   node scripts/run-eval.mjs [--gpu] [--model full|lite] [--note "..."]
import { spawn } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';

const args = process.argv.slice(2);
const flag = (name, def) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : def; };
const evalDir = resolve('..', 'eval');
const port = 5176;
const note = flag('--note', '');

const server = spawn('npx', ['vite', '--port', String(port), '--strictPort'], { stdio: 'ignore' });
try {
  for (let i = 0; i < 60; i++) {
    try { if ((await fetch(`http://localhost:${port}/label.html`)).ok) break; } catch { /* starting */ }
    await new Promise((r) => setTimeout(r, 500));
  }
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const model = flag('--model', 'full');
  const clips = [];
  for (const f of readdirSync(join(evalDir, 'labels')).filter((f) => f.endsWith('.labels.json')).sort()) {
    const labels = JSON.parse(readFileSync(join(evalDir, 'labels', f), 'utf8'));
    delete labels.frames;
    const clip = join(evalDir, 'clips', labels.video.name);
    if (!existsSync(clip)) { console.log(`skip ${f}: no clip ${labels.video.name}`); continue; }
    await page.goto(`http://localhost:${port}/label.html${args.includes('--gpu') ? '' : '?cpu'}`);
    if (model === 'lite') await page.selectOption('select >> nth=1', 'lite');
    await page.setInputFiles('#video-input', clip);
    await page.waitForFunction(() => window.__spotterEval);
    const r = await page.evaluate((l) => window.__spotterEval(l), labels);
    console.log(`${labels.video.name}: ${r.detectedReps} detected / ${r.truthReps} labelled, ${r.matched} matched`);
    clips.push(r);
  }
  const defaultNote = `Generated by \`scripts/run-eval.mjs\` on ${new Date().toISOString().slice(0, 10)} with the ${model} pose model in headless Chromium (CPU).`;
  const { report, markdown } = await page.evaluate(([c, n]) => window.__spotterReport(c, n), [clips, note || defaultNote]);
  writeFileSync(join(evalDir, 'report.json'), JSON.stringify({ report, clips }, null, 2));
  writeFileSync(join(evalDir, 'report.md'), markdown);
  console.log(markdown);
  await browser.close();
} finally {
  server.kill();
}
